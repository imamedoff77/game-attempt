#!/usr/bin/env python3
"""
Regenerates everything that shows the game's name from game.json (the single source).
Run after editing game.json:   python3 tools/sync_identity.py
It rewrites the identity block of README.md (between the identity:begin / identity:end markers) and the
"adb install" line there. The app name, package id and APK names are derived by unity-client/Assets/Editor/GameIdentity.cs
at build time, so nothing else needs editing. `--check` only reports whether README is up to date (exit code 1 if not).
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def letters(text, keep_case):
    out = "".join(c for c in text if c.isascii() and c.isalnum())
    return out if keep_case else out.lower()


def segment(text):
    s = letters(text, False)
    return "g" + s if s[:1].isdigit() else s


def load():
    with open(os.path.join(ROOT, "game.json"), encoding="utf-8") as f:
        data = json.load(f)
    name, company = data["name"].strip(), data["company"].strip()
    if not letters(name, True) or not segment(company):
        sys.exit("game.json: name and company need at least one letter or digit")
    file_name = letters(name, True)
    return {
        "name": name,
        "package": f"com.{segment(company)}.{segment(name)}",
        "apk": f"unity-client/Builds/Android/{file_name}.apk",
        "dev_apk": f"unity-client/Builds/Android/{file_name}-dev.apk",
        "dev_apk_short": f"Builds/Android/{file_name}-dev.apk",
    }


def block(v):
    return (
        "<!-- identity:begin (generated by tools/sync_identity.py from game.json, do not edit by hand) -->\n"
        f"# {v['name']}\n\n"
        "| | |\n|---|---|\n"
        f"| Ad | `{v['name']}` |\n"
        f"| Paket adı | `{v['package']}` |\n"
        f"| Buraxılış APK | `{v['apk']}` |\n"
        f"| Sınaq APK | `{v['dev_apk']}` |\n\n"
        "Ad **yalnız `game.json` faylında** saxlanır. Dəyişmək üçün: `game.json`-u düzəlt, "
        "`python3 tools/sync_identity.py` işlət, build-i təkrar qur. Tətbiqin adı, paket adı, APK adları və bu blok avtomatik yenilənir.\n"
        "<!-- identity:end -->"
    )


def main():
    v = load()
    path = os.path.join(ROOT, "README.md")
    with open(path, encoding="utf-8") as f:
        text = f.read()
    pattern = re.compile(r"<!-- identity:begin.*?<!-- identity:end -->", re.S)
    if not pattern.search(text):
        sys.exit("README.md: identity markers not found")
    new = pattern.sub(lambda m: block(v), text, count=1)
    new = re.sub(r"adb install -r Builds/Android/\S+\.apk", "adb install -r " + v["dev_apk_short"], new)
    if "--check" in sys.argv:
        if new != text:
            print("README.md is out of date: run python3 tools/sync_identity.py")
            sys.exit(1)
        print("README.md is up to date")
        return
    if new != text:
        with open(path, "w", encoding="utf-8") as f:
            f.write(new)
        print("README.md updated for:", v["name"], v["package"])
    else:
        print("README.md already up to date")


main()
